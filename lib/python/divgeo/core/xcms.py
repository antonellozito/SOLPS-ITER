def channel(k, intensity):
    """8-bit value of channel k (0 red, 1 green, 2 blue) for an
    intensity from 0 to 1."""
    table = THRESHOLDS[k]
    lo, hi = 0, 255
    while lo < hi:
        mid = (lo + hi + 1) // 2
        if table[mid] <= intensity:
            lo = mid
        else:
            hi = mid - 1
    return lo
