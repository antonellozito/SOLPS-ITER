    fluxdimp_labels = {'nFc', 2};
    fluxdims_labels = {'nFc', 2, 'ns'};
    source2dim_labels = {'nCv', 2};
    source2dims_labels = {'nCv', 2, 'ns'};
    source4dim_labels = {'nCv', 4};
    source4dims_labels = {'nCv', 4, 'ns'};

end

