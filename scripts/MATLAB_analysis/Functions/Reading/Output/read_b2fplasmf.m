    statedims = [nCv, ns];
    fluxdim = [nFc, 2];
    fluxdimp = [nFc, 2];
    fluxdims = [nFc, 2, ns];
    source2dim = [nCv, 2];
    source2dims = [nCv, 2, ns];
    source4dim = [nCv, 4];
    source4dims = [nCv, 4, ns];

